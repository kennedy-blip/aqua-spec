import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { DSP_WASM_BASE64, DSP_WASM_BYTES, DSP_WASM_SHA256 } from '../src/wasm/nephelometry_dsp.wasm.b64';
import { parseProgram, evaluate } from '../src/logic/datalog';
import { assess, boilingPoint, disinfectionDose } from '../src/elixir/aquaChemistry';
import { encodeQr, qrToSvgPath } from '../src/apk/qrCode';
const bytes = Buffer.from(DSP_WASM_BASE64, 'base64');
assert.equal(bytes.length, DSP_WASM_BYTES);
assert.equal(createHash('sha256').update(bytes).digest('hex'), DSP_WASM_SHA256);
const { instance } = await WebAssembly.instantiate(bytes, { env: { abort() { throw new Error('WASM abort'); } } });
const wasm = instance.exports as Record<string, (...args: number[]) => number>;
assert.equal(wasm.selfTest(), 100);
assert.ok(Math.abs(wasm.deltaE00(50, 2.6772, -79.7751, 50, 0, -82.7485) - 2.0425) < 0.001);
assert.ok(assess(6.1, 20, 180, 65, 22).lsi < -0.5);
assert.ok(boilingPoint(3000).boilingC > 89 && boilingPoint(3000).boilingC < 93);
const clean = disinfectionDose({ litres: 1, ntu: 1, tempC: 20, agent: { kind: 'bleach', pct: 6 } });
const cloudy = disinfectionDose({ litres: 1, ntu: 8, tempC: 20, agent: { kind: 'bleach', pct: 6 } });
assert.equal(cloudy.contactMin, 60);
assert.equal(clean.contactMin, 30);
const rules = readFileSync('src/rules/water_contaminants.dl', 'utf8');
const program = parseProgram(rules);
assert.equal(program.issues.filter(i => i.severity === 'error').length, 0);
const simple = parseProgram('reading("well", nitrate, 18.5).\nhazard(X, "nitrate") :- reading(X, nitrate, N), N > 10.');
const result = evaluate(simple);
assert.ok(result.facts.some(f => f.rel === 'hazard' && f.values[0] === 'well'));
const qr = encodeQr('https://example.com/#optics');
assert.ok(qr.size >= 21);
assert.ok(qrToSvgPath(qr, 1).length > 100);
console.log('PASS: embedded WASM checksum/self-test, reference CIEDE2000, LSI, altitude, contact time, Datalog parser/fixpoint, QR matrix.');
