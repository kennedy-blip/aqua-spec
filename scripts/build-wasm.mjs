#!/usr/bin/env node
/**
 * Compiles assembly/nephelometry_dsp.ts → assembly/build/nephelometry_dsp.wasm
 * and embeds the binary as base64 into src/wasm/nephelometry_dsp.wasm.b64.ts so
 * the Vercel bundle never depends on a WASM asset request (or on asc at runtime).
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const wasmPath = resolve(root, 'assembly/build/nephelometry_dsp.wasm');
const b64Path = resolve(root, 'src/wasm/nephelometry_dsp.wasm.b64.ts');

mkdirSync(resolve(root, 'assembly/build'), { recursive: true });
mkdirSync(dirname(b64Path), { recursive: true });

const asc = resolve(root, 'node_modules/assemblyscript/bin/asc.js');
if (!existsSync(asc)) {
  console.error('[build-wasm] assemblyscript not installed; keeping previous embedded binary.');
  process.exit(existsSync(b64Path) ? 0 : 1);
}

console.log('[build-wasm] compiling assembly/nephelometry_dsp.ts …');
execFileSync(process.execPath, [
  asc,
  'assembly/nephelometry_dsp.ts',
  '--outFile', wasmPath,
  '--runtime', 'stub',
  '--optimizeLevel', '3',
  '--shrinkLevel', '1',
  '--initialMemory', '2',
  '--stackSize', '16384',
  '--use', 'Math=NativeMath',
], { cwd: root, stdio: 'inherit' });

const bytes = readFileSync(wasmPath);
const sha = createHash('sha256').update(bytes).digest('hex');
const b64 = bytes.toString('base64');

const ts = `// AUTO-GENERATED by scripts/build-wasm.mjs — do not edit by hand.
// assembly/nephelometry_dsp.ts → AssemblyScript ${require_as_version()} → stub runtime, no host imports
// bytes: ${bytes.length}   sha256: ${sha}
export const DSP_WASM_SHA256 = '${sha}';
export const DSP_WASM_BYTES = ${bytes.length};
export const DSP_WASM_BASE64 =
  '${b64.match(/.{1,120}/g).join("' +\n  '")}';
`;

// keep the version string inline without importing package.json at runtime
function require_as_version() {
  try {
    const pkg = JSON.parse(readFileSync(resolve(root, 'node_modules/assemblyscript/package.json'), 'utf8'));
    return `v${pkg.version}`;
  } catch {
    return '';
  }
}

writeFileSync(b64Path, ts);
console.log(`[build-wasm] wrote ${wasmPath} (${bytes.length} bytes, sha256 ${sha.slice(0, 16)}…)`);
console.log(`[build-wasm] embedded base64 → ${b64Path}`);
